def fmt_fixed(v: int) -> str:
    return f"27'h{v:07x}"


def main():
    out_path = os.path.join(os.path.dirname(__file__), "..", "rtl", "bandpass_coeffs.svh")
    with open(out_path, "w") as f:
        f.write("// Auto-generated by py/gen_bandpass_coeffs.py\n")
        f.write("// Q11.16 fixed-point bandpass filterbank coefficients\n\n")

        for name, vals in COEFFS.items():
            assert len(vals) == 32, f"{name} has {len(vals)} entries, expected 32"
            fixed_vals = [to_fixed(v) for v in vals]

            # Print verification table
            for i, (fv, rv) in enumerate(zip(fixed_vals, vals)):
                # Convert back to check
                sv = fv if fv < (1 << 26) else fv - (1 << 27)
                actual = sv / SCALE
                err = abs(actual - rv)
                if rv != 0 and err / abs(rv) > 0.01:
                    print(f"  WARNING: {name}[{i}] = {rv} -> {actual} (err {err:.2e})")

            # Write SV parameter: duplicated x2 for 64 banks
            f.write(f"// {name}Table: 32 coefficients, duplicated for 64 banks\n")
            f.write(f"parameter fixed_t {name}Table[64] = '{{\n")
            line_vals = [fmt_fixed(v) for v in fixed_vals]
            # Write twice (duplicated)
            all_vals = line_vals + line_vals
            for i in range(0, 64, 8):
                chunk = ", ".join(all_vals[i:i+8])
                comma = "," if i + 8 < 64 else ""
                f.write(f"    {chunk}{comma}\n")
            f.write(f"}};\n\n")

    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()

SCALE = 1 << 16  # Q11.16
FIXED_BITS = 27
FIXED_MAX = (1 << (FIXED_BITS - 1)) - 1
FIXED_MIN = -(1 << (FIXED_BITS - 1))


def to_fixed(x: float) -> int:
    v = int(round(x * SCALE))
    v = max(FIXED_MIN, min(FIXED_MAX, v))
    # Return as unsigned 27-bit representation for SV literal
    if v < 0:
        v += 1 << FIXED_BITS
    return v


